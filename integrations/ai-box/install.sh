#!/usr/bin/env bash
# Wire kinwing into a weboko/ai-box checkout. Re-runnable; changes only what it owns.
#
#   install.sh AI_BOX_DIR [--knowledge DIR] [--export DIR] [--port 8765]
#                         [--apply-patches] [--codex-python] [--uninstall]
#
# It
#   1. links the knowledge-research and knowledge-learn skills into AI_BOX_DIR/context/skills/
#      as symlinks to /opt/kinwing/skills/<name> — a path that exists inside the boxes, where
#      this kinwing checkout is mounted read-only. entrypoint.sh then links them for Claude
#      and Codex like any other skill (after the next restart).
#   2. writes AI_BOX_DIR/docker-compose.override.yml (Compose loads it automatically, so
#      ./box picks it up): mounts the knowledge folder at /knowledge and kinwing at
#      /opt/kinwing:ro into claude, codex and box, sets KW_HOME, and adds the
#      kinwing-reader service (no credentials, no Docker socket, port on 127.0.0.1 only).
#   3. with --apply-patches: patches agent-orchestrator with max_duration (a hard wall-clock
#      limit for runs). With --codex-python: adds python3 to Dockerfile.codex (the codex-only
#      image has none; kw needs it). Both are git patches you can review in patches/.
#
# Nothing is copied into ai-box, and nothing in ai-box is committed. --uninstall removes the
# links and the generated override (patches stay; revert them with git if you want).
set -euo pipefail

here="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
kinwing="$(cd "$here/../.." && pwd)"
marker="# generated by kinwing integrations/ai-box/install.sh"

die() { echo "kinwing-install: $*" >&2; exit 1; }
usage() { sed -n '2,24p' "$0" | sed 's/^# \{0,1\}//'; }

aibox="" knowledge="" export_dir="" port=8765 patches=0 codex_py=0 uninstall=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --knowledge) knowledge="$2"; shift 2 ;;
    --export) export_dir="$2"; shift 2 ;;
    --port) port="$2"; shift 2 ;;
    --apply-patches) patches=1; shift ;;
    --codex-python) codex_py=1; shift ;;
    --uninstall) uninstall=1; shift ;;
    -h|--help) usage; exit 0 ;;
    -*) die "unknown option $1" ;;
    *) [[ -z "$aibox" ]] || die "one ai-box directory only"; aibox="$1"; shift ;;
  esac
done
[[ -n "$aibox" ]] || { usage; exit 2; }
aibox="$(cd "$aibox" && pwd)" || die "no such directory"
[[ -f "$aibox/docker-compose.yml" && -d "$aibox/context/skills" ]] || die "$aibox doesn't look like an ai-box checkout"

override="$aibox/docker-compose.override.yml"
skills=(knowledge-research knowledge-learn)

if [[ "$uninstall" == 1 ]]; then
  for s in "${skills[@]}"; do
    l="$aibox/context/skills/$s"
    if [[ -L "$l" && "$(readlink "$l")" == "/opt/kinwing/skills/$s" ]]; then rm "$l"; echo "removed link $l"; fi
  done
  if [[ -f "$override" ]] && grep -qF "$marker" "$override"; then rm "$override"; echo "removed $override"; fi
  echo "done. Recreate the boxes: ./box up -d --force-recreate <service>; the knowledge folder was left alone."
  exit 0
fi

knowledge="${knowledge:-$aibox/../knowledge}"
mkdir -p "$knowledge"
knowledge="$(cd "$knowledge" && pwd)"
case "$knowledge/" in
  "$aibox"/claude-box/*|"$aibox"/codex-box/*|"$aibox"/ai-box/*)
    die "keep the knowledge folder outside the boxes' homes (it is shared between them)" ;;
esac
if [[ -n "$export_dir" ]]; then
  mkdir -p "$export_dir"
  export_dir="$(cd "$export_dir" && pwd)"
fi
[[ "$port" =~ ^[0-9]+$ ]] || die "--port must be a number"

# 1. skills
for s in "${skills[@]}"; do
  l="$aibox/context/skills/$s"
  if [[ -e "$l" && ! -L "$l" ]]; then
    die "$l exists and is not kinwing's link; move it aside first"
  fi
  ln -sfn "/opt/kinwing/skills/$s" "$l"
  echo "linked $l -> /opt/kinwing/skills/$s (resolves inside the boxes)"
done

# 2. compose override
if [[ -f "$override" ]] && ! grep -qF "$marker" "$override"; then
  die "$override exists and wasn't written by kinwing. Merge integrations/ai-box/README.md's snippet into it by hand."
fi
agent_block() {
  cat <<EOF
  $1:
    volumes:
      - $knowledge:/knowledge
      - $kinwing:/opt/kinwing:ro
EOF
  [[ -n "$export_dir" ]] && echo "      - $export_dir:/exports"
  cat <<EOF
    environment:
      KW_HOME: /knowledge
EOF
  [[ -n "$export_dir" ]] && echo "      KW_EXPORT_DIR: /exports"
  return 0
}
{
  echo "$marker"
  echo "# Re-run install.sh to regenerate; --uninstall removes it. kinwing: $kinwing"
  echo "services:"
  agent_block claude
  agent_block codex
  agent_block box
  cat <<EOF
  # The private reader. Only the knowledge folder is mounted: no agent homes, no
  # credentials, no Docker socket. Published on the host's loopback only; on a VPS use
  # ssh -L $port:127.0.0.1:$port <host>.
  kinwing-reader:
    build:
      context: $kinwing
    image: kinwing:latest
    container_name: kinwing-reader
    restart: unless-stopped
    init: true
    read_only: true
    tmpfs: [/tmp]
    cap_drop: [ALL]
    security_opt: [no-new-privileges:true]
    environment:
      KW_HOME: /knowledge
EOF
  [[ -n "$export_dir" ]] && echo "      KW_EXPORT_DIR: /exports"
  cat <<EOF
    env_file:
      - path: .env
        required: false
    volumes:
      - $knowledge:/knowledge
EOF
  [[ -n "$export_dir" ]] && echo "      - $export_dir:/exports"
  cat <<EOF
    ports:
      - "127.0.0.1:$port:8765"
EOF
} > "$override.tmp"
mv "$override.tmp" "$override"
echo "wrote $override"

# 3. patches
apply_patch() {
  local p="$here/patches/$1"
  if git -C "$aibox" apply --reverse --check "$p" >/dev/null 2>&1; then
    echo "patch $1: already applied"
  elif git -C "$aibox" apply --check "$p" >/dev/null 2>&1; then
    git -C "$aibox" apply "$p"
    echo "patch $1: applied (review: git -C $aibox diff)"
  else
    echo "patch $1: does not apply to this ai-box version; see $p" >&2
  fi
}
[[ "$patches" == 1 ]] && apply_patch 0001-agent-orchestrator-max-duration.patch
[[ "$codex_py" == 1 ]] && apply_patch 0002-codex-image-python3.patch

cat <<EOF

kinwing is wired in. Knowledge folder: $knowledge
Next:
  cd $aibox
  ./box build kinwing-reader
  ./box up -d --force-recreate <claude|codex|box> kinwing-reader      # add --build after --codex-python
  ./box exec <service> /opt/box-context/skills/knowledge-research/bin/kw status
Reader: http://localhost:$port/   (from elsewhere: ssh -L $port:127.0.0.1:$port <this host>)
Then ask Claude or Codex: "Start researching <topic> …"
EOF
