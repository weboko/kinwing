"""The evolving research dossier of a topic, and the kb README index.

`topics/<id>/dossier.md` = the agent's narrative (`overview.md`, rewritten as understanding
improves) + sections generated from the records: concepts, conclusions by strength with
their evidence, conflicts, uncertainties, the question queue, next investigations,
sources and recent changes. It is regenerated after every run and never edited by hand,
so it can't drift from the evidence. `changes.md` renders the full change history.
"""

from __future__ import annotations

import datetime as dt

from . import store
from .kb import KB
from .store import now, parse_ts

STRENGTH_ORDER = ["strong", "moderate", "weak", "contested", "unsupported"]


def _l(kind: str, eid: str, label: str | None = None) -> str:
    folder = store.KIND_DIRS[kind]
    return f"[{label or eid}](../../{folder}/{eid}.md)"


def _quote(s: str, n: int = 240) -> str:
    s = " ".join((s or "").split())
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def build(kb: KB, topic: str) -> str:
    t = kb.topic(topic)
    d = kb.p.topic_dir(topic)
    overview = (d / "overview.md").read_text(encoding="utf-8") if (d / "overview.md").exists() else ""
    concepts = sorted(kb.metas("concept", topic), key=lambda c: c.get("title", ""))
    claims_all = kb.metas("claim", topic)
    claims = [c for c in claims_all if c.get("state") == "current"]
    ev = {e["id"]: e for e in kb.metas("evidence")}
    src = {s["id"]: s for s in kb.metas("source")}
    qs = kb.metas("question", topic)
    runs = sorted([r for r in kb.metas("run") if r.get("topic") == topic], key=lambda r: r.get("started") or "")
    changes = kb.changes(topic)

    def ev_ref(eid: str) -> str:
        e = ev.get(eid)
        if not e:
            return f"`{eid}` (missing)"
        s = src.get(e.get("source"), {})
        loc = f" {e['locator']}" if e.get("locator") else ""
        return f"{_l('evidence', eid)} ← {_l('source', e.get('source', ''), s.get('title') or e.get('source'))}{loc}"

    out = [
        f"# {t['title']} — research dossier",
        "",
        f"> Generated by kinwing on {now()} from the records in this knowledge base. Don't edit it; "
        "edit `overview.md` (the narrative) or the records, then `kw dossier " + topic + "`.",
        "",
        f"- **Objective:** {t.get('objective') or '—'}",
        f"- **Your familiarity going in:** {t.get('familiarity') or '—'}",
        f"- **Depth:** {t.get('depth')} · **status:** {t.get('status')} · **last investigated:** "
        f"{t.get('last_investigated') or 'never'} · **runs:** {len(runs)}",
        f"- **Size:** {len(concepts)} concepts · {len(claims)} current claims · "
        f"{len([e for e in ev.values() if topic in (e.get('topics') or [])])} evidence records · "
        f"{len([s for s in src.values() if topic in (s.get('topics') or [])])} sources · "
        f"{sum(1 for q in qs if q.get('status') == 'open')} open questions",
        "",
        "## 1. Orientation",
        "",
        _strip_h1(overview).strip() or "_No orientation written yet._",
        "",
        "## 2. Main concepts",
        "",
    ]
    if concepts:
        for c in concepts:
            extra = []
            if c.get("prerequisites"):
                extra.append("builds on " + ", ".join(f"`{p}`" for p in c["prerequisites"]))
            rel = [f"{r.get('rel')} `{r.get('id')}`" for r in c.get("related") or []]
            if rel:
                extra.append("; ".join(rel))
            out.append(f"- **{_l('concept', c['id'], c.get('title'))}** — {c.get('summary') or '…'}"
                       + (f" _({'; '.join(extra)})_" if extra else ""))
    else:
        out.append("_None yet._")
    out += ["", "## 3. Current conclusions", "",
            "Strength is an assessment of the evidence, not a probability. Kinds: **finding** "
            "(directly supported), **interpretation** (a reading of the evidence), **hypothesis** "
            "(plausible, not yet supported).", ""]
    if claims:
        for strength in STRENGTH_ORDER:
            group = [c for c in claims if c.get("strength") == strength]
            if not group:
                continue
            out.append(f"### {strength.capitalize()}")
            out.append("")
            for c in group:
                out.append(f"- **{c['text']}** — {c.get('kind')} · {_l('claim', c['id'])} · verified {c.get('last_verified')}")
                for e in c.get("support") or []:
                    out.append(f"  - supports: {ev_ref(e)}")
                for e in c.get("counter") or []:
                    out.append(f"  - **against:** {ev_ref(e)}")
                if c.get("uncertainty"):
                    out.append(f"  - uncertainty: {c['uncertainty']}")
            out.append("")
    else:
        out += ["_No conclusions yet._", ""]

    out += ["## 4. Supporting evidence", ""]
    topic_ev = [e for e in ev.values() if topic in (e.get("topics") or [])]
    if topic_ev:
        for e in sorted(topic_ev, key=lambda e: (e.get("source", ""), e.get("created", ""))):
            s = src.get(e.get("source"), {})
            text = f"“{_quote(e.get('quote'))}”" if e.get("quote") else f"_(observation)_ {_quote(e.get('note'))}"
            flag = "" if e.get("quote_verified") or not e.get("quote") else " ⚠ unverified quote"
            out.append(f"- {_l('evidence', e['id'])}: {text} — {s.get('title') or e.get('source')}"
                       f"{(' ' + e['locator']) if e.get('locator') else ''}{flag}")
            if e.get("note") and e.get("quote"):
                out.append(f"  - note (AI): {_quote(e['note'], 300)}")
    else:
        out.append("_None yet._")
    out += ["", "## 5. Competing explanations and conflicts", ""]
    conflicts = [c for c in claims if c.get("strength") == "contested" or c.get("contradicts") or c.get("counter")]
    if conflicts:
        idx = {c["id"]: c for c in claims_all}
        done = set()
        for c in conflicts:
            if c["id"] in done:
                continue
            done.add(c["id"])
            out.append(f"- {_l('claim', c['id'])}: {c['text']}")
            for o in c.get("contradicts") or []:
                done.add(o)
                if o in idx:
                    out.append(f"  - vs {_l('claim', o)}: {idx[o]['text']}")
            if c.get("counter"):
                out.append(f"  - counter-evidence or caveat ({c.get('strength')}): "
                           + "; ".join(ev_ref(e) for e in c["counter"]))
    else:
        out.append("_No conflicts recorded._")
    out += ["", "## 6. Important uncertainties", ""]
    unc = [c for c in claims if c.get("kind") == "hypothesis" or c.get("strength") in ("weak", "unsupported")
           or c.get("uncertainty") or c.get("needs_verification")]
    stale_cut = dt.datetime.now(dt.timezone.utc) - dt.timedelta(days=int(t.get("stale_after_days") or 180))
    for c in unc:
        why = c.get("uncertainty") or f"{c.get('strength')} {c.get('kind')}"
        out.append(f"- {c['text']} ({_l('claim', c['id'])}) — {why}")
    for c in claims:
        if (parse_ts(c.get("last_verified")) or stale_cut) < stale_cut:
            out.append(f"- Possibly stale: {c['text']} (last verified {c.get('last_verified')})")
    if not unc:
        out.append("_None recorded._")
    out += ["", "## 7. Research questions", ""]
    ranked = {q["id"]: (s, why) for s, why, q in kb.ranked_questions(topic, ("open", "in_progress", "partial", "blocked"))}
    for status in ("in_progress", "open", "partial", "blocked", "answered", "dropped"):
        group = [q for q in qs if q.get("status") == status]
        if not group:
            continue
        group.sort(key=lambda q: -ranked.get(q["id"], (0, ""))[0])
        out.append(f"### {status.replace('_', ' ').capitalize()} ({len(group)})")
        out.append("")
        for q in group:
            sc = ranked.get(q["id"])
            meta = f"{q.get('origin')}" + (f", {q.get('perspective')}" if q.get("perspective") else "")
            meta += f", score {sc[0]:g}" if sc else ""
            out.append(f"- {_l('question', q['id'])} {q['text']} _({meta})_")
            if q.get("result"):
                out.append(f"  - result: {_quote(q['result'], 400)}")
        out.append("")
    if not qs:
        out += ["_No questions yet._", ""]
    out += ["## 8. Recommended next investigations", ""]
    nxt = [x for x in kb.ranked_questions(topic) if x[0] >= 0][:5]
    for s, why, q in nxt:
        out.append(f"1. {q['text']} — {_l('question', q['id'])} (score {s:g}: {why})")
    if runs and runs[-1].get("next_steps"):
        out.append("")
        out.append(f"The last run ({runs[-1]['id']}) suggested:")
        out += [f"- {x}" for x in runs[-1]["next_steps"]]
    gaps = [pz for pz in t.get("perspectives") or [] if not any(q.get("perspective") == pz["id"] for q in qs)]
    if gaps:
        out.append("")
        out.append("Perspectives without questions yet: " + ", ".join(pz["name"] for pz in gaps))
    if not nxt and not gaps and not (runs and runs[-1].get("next_steps")):
        out.append("_Nothing queued._")
    out += ["", "## 9. Sources", ""]
    tsrc = sorted([s for s in src.values() if topic in (s.get("topics") or [])], key=lambda s: (s.get("category", ""), s.get("title", "")))
    for s in tsrc:
        if s.get("access") == "wanted":
            continue
        where = s.get("canonical_url") or ("local file" if s.get("local_path") else "")
        out.append(f"- {_l('source', s['id'], s.get('title'))} — {s.get('category')}, {where}"
                   f"{', retrieved ' + s['retrieved'][:10] if s.get('retrieved') else ''}"
                   f"{', rights: ' + s['rights'] if s.get('rights') not in ('open', 'unknown') else ''}")
    wanted = [s for s in tsrc if s.get("access") == "wanted"]
    if wanted:
        out += ["", "**To acquire** (legal copies only; not fetched automatically):", ""]
        out += [f"- {s.get('title')}{' — ' + ', '.join(s.get('authors') or []) if s.get('authors') else ''}"
                f"{' (ISBN ' + s['isbn'] + ')' if s.get('isbn') else ''}: {s.get('why') or ''}" for s in wanted]
    if not tsrc:
        out.append("_None yet._")
    out += ["", "## 10. Recent changes", ""]
    for c in changes[-25:][::-1]:
        out.append(f"- {c['at'][:16].replace('T', ' ')} · {c['summary']}" + (f" _({c['run']})_" if c.get("run") else ""))
        if c.get("detail"):
            out.append(f"  - why: {_quote(c['detail'], 300)}")
    out += ["", "Full history: [changes.md](changes.md) · runs: " +
            (", ".join(_l("run", r["id"]) for r in runs[-8:]) or "none")]
    text = "\n".join(out).rstrip() + "\n"
    store.atomic_write(d / "dossier.md", text)
    store.atomic_write(d / "changes.md", render_changes(t, changes))
    build_index(kb)
    return text


def _strip_h1(md: str) -> str:
    lines = md.strip().splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    return "\n".join(l for l in lines if not l.strip().startswith("<!-- kinwing:"))


def render_changes(t: dict, changes: list[dict]) -> str:
    out = [f"# {t['title']} — change history", "",
           "> Generated from `changes.jsonl` (append-only). Newest first.", ""]
    for c in changes[::-1]:
        out.append(f"- **{c['at']}** · {c['kind']} `{c['id']}` · {c['summary']}" + (f" · run `{c['run']}`" if c.get("run") else ""))
        if c.get("detail"):
            out.append(f"  - {c['detail']}")
    return "\n".join(out) + "\n"


def build_index(kb: KB) -> None:
    lines = ["# Knowledge base", "",
             "> Maintained by kinwing (`kw`). Records are Markdown with YAML frontmatter; "
             "`topics/<id>/dossier.md` is the readable synthesis of each topic.", "",
             "| Topic | Status | Depth | Concepts | Claims | Open questions | Last investigated |",
             "|---|---|---|---|---|---|---|"]
    for t in kb.topics():
        tid = t["id"]
        lines.append(
            f"| [{t['title']}](topics/{tid}/dossier.md) | {t.get('status')} | {t.get('depth')} | "
            f"{len(kb.metas('concept', tid))} | "
            f"{sum(1 for c in kb.metas('claim', tid) if c.get('state') == 'current')} | "
            f"{sum(1 for q in kb.metas('question', tid) if q.get('status') == 'open')} | "
            f"{(t.get('last_investigated') or 'never')[:10]} |")
    lines += ["", "Folders: `topics/` (config, overview, dossier, changes), `questions/`, `sources/` "
              "(metadata; text lives in `../library/`), `evidence/`, `claims/`, `concepts/`, `runs/`.", ""]
    store.atomic_write(kb.p.kb / "README.md", "\n".join(lines))
